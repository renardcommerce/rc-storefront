import { Container, clx } from "@medusajs/ui"
import Image from "next/image"
import React from "react"

import PlaceholderImage from "@modules/common/icons/placeholder-image"

type ThumbnailProps = {
  thumbnail?: string | null
  // TODO: Fix image typings
  images?: any[] | null
  size?: "small" | "medium" | "large" | "full" | "square"
  isFeatured?: boolean
  // Tweede foto, alleen zichtbaar bij hover op desktop.
  hoverImage?: string | null
  className?: string
  "data-testid"?: string
}

const Thumbnail: React.FC<ThumbnailProps> = ({
  thumbnail,
  images,
  size = "small",
  isFeatured,
  hoverImage,
  className,
  "data-testid": dataTestid,
}) => {
  const initialImage = thumbnail || images?.[0]?.url

  return (
    <Container
      className={clx(
        "relative w-full overflow-hidden p-4 bg-bone border-0 shadow-card rounded-large group-hover:shadow-card-hover transition-shadow ease-in-out duration-200",
        className,
        {
          "aspect-square": isFeatured,
          "aspect-[9/16]": !isFeatured && size !== "square",
          "aspect-[1/1]": size === "square",
          "w-[180px]": size === "small",
          "w-[290px]": size === "medium",
          "w-[440px]": size === "large",
          "w-full": size === "full",
        }
      )}
      data-testid={dataTestid}
    >
      <ImageOrPlaceholder image={initialImage} size={size} />
      {initialImage && hoverImage && (
        <div className="absolute inset-0 hidden bg-bone opacity-0 transition-opacity duration-300 small:block [@media(hover:hover)]:group-hover:opacity-100">
          <Image
            src={hoverImage}
            alt=""
            className="object-contain object-center p-8 mix-blend-multiply"
            draggable={false}
            quality={50}
            sizes="(max-width: 1440px) 25vw, 360px"
            loading="lazy"
            fill
          />
        </div>
      )}
    </Container>
  )
}

const ImageOrPlaceholder = ({
  image,
  size,
}: Pick<ThumbnailProps, "size"> & { image?: string }) => {
  return image ? (
    <Image
      src={image}
      alt=""
      className="absolute inset-0 object-contain object-center p-4 mix-blend-multiply"
      draggable={false}
      quality={50}
      sizes="(max-width: 576px) 280px, (max-width: 768px) 360px, (max-width: 992px) 480px, 800px"
      fill
    />
  ) : (
    <div className="w-full h-full absolute inset-0 flex items-center justify-center">
      <PlaceholderImage size={size === "small" ? 16 : 24} />
    </div>
  )
}

export default Thumbnail
